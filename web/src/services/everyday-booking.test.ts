import { expect, it } from "vitest";
import { createOperatorBooking, listBookingEmails, sendBookingDetails, cancelBooking } from "./bookings.service";
import { listClients } from "./clients.service";
import { createSession, getSession, listBookableSessions } from "./sessions.service";
import { listServices } from "./services.service";
it("simulates atomic last-seat creation, retries and reviewed email recovery without changing showcase dates", async () => {
  const service = (await listServices())[0];
  const session = await createSession({ serviceId: service.id, startISO: "2030-05-01T10:00:00Z", endISO: "2030-05-01T11:00:00Z", capacity: 1, bookedCount: 0, status: "scheduled", locationType: "online", location: "Demo", recurring: "one-off" });
  const before = (await listClients()).length;
  const input = { newClient: { name: "Demo booking client", email: "demo-booking@example.com" }, sessionId: session.id, auditReason: "Demo", sendEmail: false, language: "de" as const };
  const [first, second] = await Promise.allSettled([createOperatorBooking(input, "demo-first"), createOperatorBooking({ ...input, newClient: { name: "Other", email: "other-demo@example.com" } }, "demo-second")]);
  expect(first.status).toBe("fulfilled");
  expect(second.status).toBe("rejected");
  if (first.status !== "fulfilled") return;
  expect((await listClients()).length).toBe(before + 1);
  expect((await getSession(session.id))?.bookedCount).toBe(1);
  expect((await listBookableSessions()).items.some((s) => s.id === session.id)).toBe(false);
  expect((await createOperatorBooking(input, "demo-first")).id).toBe(first.value.id);
  expect((await listBookingEmails(first.value.id)).items).toEqual([]);
  const fixed = await sendBookingDetails(first.value.id, "corrected-demo@example.com", "demo-send");
  await sendBookingDetails(first.value.id, "corrected-demo@example.com", "demo-send");
  expect(fixed.customer?.email).toBe("demo-booking@example.com");
  const history = await listBookingEmails(first.value.id);
  expect(history.total).toBe(1);
  expect(history.items[0].simulated).toBe(true);
  expect(history.items[0].recipientEmail).toBe("corrected-demo@example.com");
  await expect(sendBookingDetails(first.value.id, "other@example.com", "demo-send")).rejects.toMatchObject({ status: 409 });
  await cancelBooking(first.value.id);
  expect((await getSession(session.id))?.bookedCount).toBe(0);
});
